export const STRINGS: Record<Lang, Dict> = { en, ja };

export function translate(
  lang: Lang,
  key: string,
  vars?: Record<string, string | number>
): string {
  let s = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
  if (vars) for (const k in vars) s = s.replace(`{${k}}`, String(vars[k]));
  return s;
}

/**
 * Split a string on the `|` phrase marker.
 *
 * Japanese has no spaces, so a browser will happily break a line in the middle
 * of a 文節 — the tagline used to wrap as "実験室にいなくて / も、", stranding
 * "も、" at the head of the next line. `word-break: auto-phrase` fixes this
 * automatically but only ships in Chromium, so the breakable points are marked
 * in the string itself and each phrase is rendered as an inline-block that the
 * browser will not break inside.
 *
 * A string with no `|` comes back as a single phrase, which wraps normally.
 */
export function phrases(text: string): string[] {
  return text.split("|");
}
